// Validate declared routes against the actual handlers so the reference cannot silently drift.
const source = readFileSync('server/app.ts', 'utf8');
for (const route of ROUTES) {
  const path = route.path.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  if (!new RegExp(`app\\.${route.method.toLowerCase()}\\(\\s*['"]${path}['"]`).test(source))
    throw new Error(`Missing API handler: ${route.method} ${route.path}`);
}
let drift = false;
for (const [path, content] of Object.entries(outputs)) {
  if (check) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) {
      console.error(`Out of date: ${path}`);
      drift = true;
    }
  } else {
    mkdirSync(resolve(path, '..'), { recursive: true });
    writeFileSync(path, content);
  }
}
if (drift) process.exit(1);
console.log(
  check
    ? 'Generated documentation is synchronized.'
    : 'Generated agent context, API registry, documentation matrix, and data matrix.',
);
